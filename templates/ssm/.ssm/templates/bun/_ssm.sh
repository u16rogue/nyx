# cwd is the stage root, has to create ./<name>
ssm_tpl_scaffold() {
    bun init --yes "$1" < /dev/null || return 1
    # bun init adds agent rules when it detects claude/cursor, the project has its AGENTS.md
    rm -rf -- "$1/CLAUDE.md" "$1/.cursor"
}

# cwd is the staged subproject with the template files overlaid
ssm_tpl_stage() {
    bun pm pkg set version="$2" scripts.postinstall="bun scripts/bun2nix.ts -o bun.lock.nix" || return 1
    # installs everything, the postinstall then generates bun.lock.nix from bun.lock
    bun add --dev bun2nix || return 1
    # shellcheck disable=SC2016
    if ! grep -q '^# Autogenerated by `bun2nix`' bun.lock.nix; then
        printErr "bun2nix didn't generate bun.lock.nix"
        return 1
    fi
}

# cwd is the subproject in place, fills the covered node_modules
ssm_tpl_finalize() {
    bun install --frozen-lockfile
}
