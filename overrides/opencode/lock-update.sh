#!/usr/bin/env bash
# THIS WAS WRITTEN BY A CLANKER
# Pins the opencode GitHub release into lock.nix beside this script.
# usage: lock-update.sh [version]   (defaults to the highest stable vX.Y.Z tag)
# GitHub's "latest" flag can point at a maintenance branch, so releases are sorted by version instead.
# Set GITHUB_TOKEN to avoid API rate limits.
set -euo pipefail

printErr() {
    printf '\033[37m[\033[91merr\033[37m]\033[0m %s\n' "$1" >&2
}

printWarn() {
    printf '\033[37m[\033[93mwarn\033[37m]\033[0m %s\n' "$1" >&2
}

printLog() {
    printf '\033[37m[log]\033[0m %s\n' "$1" >&2
}

die() {
    printErr "$1"
    exit 1
}

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
missing_cmds=()
missing_pkgs=()
if ! command -v "curl" &> /dev/null; then missing_cmds+=("curl"); missing_pkgs+=("nixpkgs#curl"); fi
if ! command -v "jq" &> /dev/null; then missing_cmds+=("jq"); missing_pkgs+=("nixpkgs#jq"); fi
if ! command -v "basenc" &> /dev/null; then missing_cmds+=("basenc"); missing_pkgs+=("nixpkgs#coreutils"); fi
if (( ${#missing_cmds[@]} )); then
    if [[ -n "${_SOFTDEPS_REEXEC:-}" ]]; then die "still missing after nix shell: ${missing_cmds[*]}"; fi
    if ! command -v "nix" &> /dev/null; then die "missing dependencies, please install: ${missing_cmds[*]}"; fi
    printWarn "missing ${missing_cmds[*]}, rerunning in a nix shell"
    _SOFTDEPS_REEXEC=1 exec nix --extra-experimental-features 'nix-command flakes' shell --inputs-from "$script_dir" "${missing_pkgs[@]}" --command "${BASH_SOURCE[0]}" "$@"
fi

repo="anomalyco/opencode"
target="$script_dir/lock.nix"
# nix system -> release asset
declare -A assets=(
    [x86_64-linux]="opencode-linux-x64.tar.gz"
    [aarch64-linux]="opencode-linux-arm64.tar.gz"
)

githubApi() {
    local auth=()
    if [[ -n "${GITHUB_TOKEN:-}" ]]; then auth=(--header "Authorization: Bearer $GITHUB_TOKEN"); fi
    curl --fail --location --retry 3 --silent --show-error \
        --header "Accept: application/vnd.github+json" "${auth[@]}" \
        "https://api.github.com/repos/$repo/$1"
}

if [[ -n "${1:-}" ]]; then
    tag="v${1#v}"
else
    printLog "looking up the newest release of $repo"
    tag="$(githubApi "releases?per_page=100" | jq --raw-output '
        [ .[] | select((.draft | not) and (.prerelease | not) and (.tag_name | test("^v[0-9]+\\.[0-9]+\\.[0-9]+$"))) ]
        | max_by(.tag_name | ltrimstr("v") | split(".") | map(tonumber))
        | .tag_name // empty
    ')"
    if [[ -z "$tag" ]]; then die "no stable release found"; fi
fi
version="${tag#v}"

printLog "fetching metadata for $tag"
release="$(githubApi "releases/tags/$tag")" || die "release $tag not found"

temporary="$(mktemp "$script_dir/.lock.nix.XXXXXX")"
trap 'rm -f "$temporary"' EXIT
{
    printf '# generated by lock-update.sh, do not edit\n'
    printf '{\n'
    printf '    version = "%s";\n' "$version"
    printf '    assets = {\n'
    for system in $(printf '%s\n' "${!assets[@]}" | sort); do
        name="${assets[$system]}"
        asset="$(jq --compact-output --arg name "$name" '.assets[] | select(.name == $name)' <<< "$release")"
        if [[ -z "$asset" ]]; then die "$tag has no asset $name"; fi
        url="$(jq --raw-output '.browser_download_url' <<< "$asset")"
        digest="$(jq --raw-output '.digest // empty' <<< "$asset")"
        if [[ ! "$digest" =~ ^sha256:[0-9a-fA-F]{64}$ ]]; then die "$name has no usable sha256 digest ($digest)"; fi
        hex="${digest#sha256:}"
        hash="sha256-$(printf '%s' "${hex^^}" | basenc --base16 --decode | base64 --wrap=0)"
        printLog "pinned $system -> $name"
        printf '        %s = {\n' "$system"
        printf '            url = "%s";\n' "$url"
        printf '            hash = "%s";\n' "$hash"
        printf '        };\n'
    done
    printf '    };\n'
    printf '}\n'
} > "$temporary"

mv "$temporary" "$target"
printLog "wrote $target ($version)"
